"""Data sources registry: provenance, licence, restrictions and verified access path of every
dataset used by BANKVERSE AI.

Verification policy
-------------------
* ``sha256``  : exact content hash published by the owner (e.g. Git LFS object id) → byte-exact check.
* ``git_blob``: SHA-1 git blob id of the file in a pinned public repository → byte-exact check
  against the repository content.
* ``facts``   : for mirrors of UCI datasets, the content is verified against the facts published by
  the original owner (row counts, class counts) during the silver step.

Sources whose licence forbids commercial reuse, or that are not reachable from the execution
environment, are registered with an explicit status and are *not* imported silently.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from sqlalchemy.dialects.postgresql import insert

