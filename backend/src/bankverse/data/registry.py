SOURCES_BY_KEY = {s.key: s for s in SOURCES}


def sync_registry() -> dict[str, Any]:
    """Upsert the registry into ``platform.data_sources`` (owner role: the table is read-only for the API)."""
    with control_session(owner=True) as db:
        for s in SOURCES:
            values = {
                "key": s.key, "name": s.name, "owner": s.owner, "kind": s.kind, "license": s.license,
                "restrictions": s.restrictions, "redistribution": s.redistribution,
                "original_url": s.original_url,
                "access_url": "; ".join(f.url for f in s.files) or None,
                "modules": list(s.modules), "access_status": s.access_status, "access_note": s.access_note,
                "commercial_use_ok": s.commercial_use_ok,
                "meta": {"expected": s.expected, "files": [f.filename for f in s.files]},
            }
            stmt = insert(DataSource).values(**values)
            update_cols = {k: stmt.excluded[k] for k in values if k not in ("key",)}
            # Keep an access status already measured by a real ingestion run.
            update_cols.pop("access_status")
            db.execute(stmt.on_conflict_do_update(index_elements=[DataSource.key], set_=update_cols))
    return {"registered": len(SOURCES)}
